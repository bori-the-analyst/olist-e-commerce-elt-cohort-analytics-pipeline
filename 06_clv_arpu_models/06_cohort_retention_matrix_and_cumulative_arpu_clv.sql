/* ARPU and CLV Model
ARPU (Average Revenue Per User) & CLV model tells how much economic value each customer generates over time.
By dividing total monthly revenue by the initial cohort size (M_0 baseline users) and calculating a running sum across subsequent months, monetization curve of the customer base can be mapped.

Objectives:
Monthly ARPU; financial return generated by that cohort during a specific month_index
Cumulative CLV: monetization trajectory over time
**/

-- 1. Aggregate revenue and active users per cohort and month index
WITH monthly_metrics AS (
    SELECT 
        cohort_month,
        month_index,
        COUNT(DISTINCT customer_unique_id) AS active_users,
        SUM(total_order_value) AS monthly_revenue
    FROM analytics.fct_customer_cohorts
    GROUP BY cohort_month, month_index
),
-- 2. Get initial cohort size (M_0 base users)
cohort_sizes AS (
    SELECT 
        cohort_month, 
        COUNT(DISTINCT customer_unique_id) AS initial_size
    FROM analytics.fct_customer_cohorts
    WHERE month_index = 0
    GROUP BY cohort_month
)
-- 3. Calculate Monthly ARPU and Cumulative CLV per Cohort Vintage
SELECT 
    m.cohort_month,
    s.initial_size,
    m.month_index,
    m.active_users,
    ROUND(m.monthly_revenue, 2) AS monthly_revenue,
    -- ARPU for the specific month index (normalized by initial cohort size)
    ROUND(m.monthly_revenue / s.initial_size, 2) AS monthly_arpu,
    -- Cumulative CLV (Running total of ARPU from M_0 up to current month_index)
    ROUND(
        SUM(m.monthly_revenue / s.initial_size) OVER (
            PARTITION BY m.cohort_month 
            ORDER BY m.month_index 
            ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
        ), 2
    ) AS cumulative_clv
FROM monthly_metrics m
JOIN cohort_sizes s ON m.cohort_month = s.cohort_month
ORDER BY m.cohort_month, m.month_index;



