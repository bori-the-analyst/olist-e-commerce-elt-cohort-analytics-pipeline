-- 6.1.2 Extracting business value from Cohort table.
-- 6.1.2.1 Calculate Initial Cohort Sizes (M_0 Acquisition month)
WITH cohort_sizes AS (
    SELECT 
        cohort_month,
        COUNT(DISTINCT customer_unique_id) AS initial_cohort_size
    FROM analytics.fct_customer_cohorts
    WHERE month_index = 0
    GROUP BY cohort_month
),
-- 6.1.2.2 Calculate Active Users per Cohort across every Month Index (M_0 through M_n)
cohort_activity AS (
    SELECT 
        cohort_month,
        month_index,
        COUNT(DISTINCT customer_unique_id) AS active_users
    FROM analytics.fct_customer_cohorts
    GROUP BY cohort_month, month_index
)
-- 6.1.2.3 Combine to compute retention percentages
SELECT 
    a.cohort_month,
    s.initial_cohort_size,
    a.month_index,
    a.active_users,
    ROUND(100.0 * a.active_users / s.initial_cohort_size, 2) AS retention_percentage
FROM cohort_activity a
JOIN cohort_sizes s ON a.cohort_month = s.cohort_month
ORDER BY a.cohort_month, a.month_index;


-- Creating pivoted matrix (Rows = Cohort Months, Columns = M_0, M_1, M_2,....).
-- This matrix can be comprehended more easily even by non-technical audience
WITH cohort_sizes AS (
    SELECT cohort_month, COUNT(DISTINCT customer_unique_id) AS initial_size
    FROM analytics.fct_customer_cohorts WHERE month_index = 0 GROUP BY cohort_month
),
activity AS (
    SELECT cohort_month, month_index, COUNT(DISTINCT customer_unique_id) AS active_users
    FROM analytics.fct_customer_cohorts GROUP BY cohort_month, month_index
)
SELECT 
    a.cohort_month,
    s.initial_size,
    ROUND(100.0 * SUM(CASE WHEN a.month_index = 0 THEN a.active_users ELSE 0 END) / s.initial_size, 1) AS "M_0",
    ROUND(100.0 * SUM(CASE WHEN a.month_index = 1 THEN a.active_users ELSE 0 END) / s.initial_size, 1) AS "M_1",
    ROUND(100.0 * SUM(CASE WHEN a.month_index = 2 THEN a.active_users ELSE 0 END) / s.initial_size, 1) AS "M_2",
    ROUND(100.0 * SUM(CASE WHEN a.month_index = 3 THEN a.active_users ELSE 0 END) / s.initial_size, 1) AS "M_3",
    ROUND(100.0 * SUM(CASE WHEN a.month_index = 6 THEN a.active_users ELSE 0 END) / s.initial_size, 1) AS "M_6",
    ROUND(100.0 * SUM(CASE WHEN a.month_index = 12 THEN a.active_users ELSE 0 END) / s.initial_size, 1) AS "M_12"
FROM activity a
JOIN cohort_sizes s ON a.cohort_month = s.cohort_month
GROUP BY a.cohort_month, s.initial_size
ORDER BY a.cohort_month;


